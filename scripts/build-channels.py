"""Builds belgie.channels.xml from the full Pickx channel list.

Usage:
  gh api repos/iptv-org/epg/contents/sites/pickx.be/pickx.be.channels.xml -H "Accept: application/vnd.github.raw" > pickx.xml
  curl -sSLo channels.json https://iptv-org.github.io/api/channels.json
  python3 scripts/build-channels.py pickx.xml channels.json belgie.channels.xml channels-meta.json

channels-meta.json (published next to the guide as channels.json) gives the app each channel's
language and categories, for the filters above the grid.
"""
import json, re, sys, collections
from xml.sax.saxutils import escape
pickx_path, api_path, out_path, meta_path = sys.argv[1:5]
rows = re.findall(r'<channel site="pickx.be" site_id="([^"]*)" lang="([^"]*)" xmltv_id="([^"]*)">([^<]*)</channel>', open(pickx_path).read())
db = {c['id']: c for c in json.load(open(api_path))}

CORE = ["VRT1.be@SD","VTM.be@SD","Play4.be@SD","VRTCanvas.be@SD","VTM2.be@SD","Play5.be@SD",
        "VTM3.be@SD","Ketnet.be@SD","VTM4.be@SD","Play6.be@SD","LaUne.be@SD","RTLTVI.be@SD"]
ADULT = re.compile(r'xxx|dorcel|penthouse|playboy|hustler', re.I)
skipped = collections.Counter()

def feed_key(xid):            # VRT1.be@SD / VRT1.be@HD -> VRT1.be@ ; X@FRHD -> X@FR
    return re.sub(r'(HD|SD)$', '', xid)

def prefer(a, b):             # SD before HD, then first in file
    return a if not a[2].endswith('HD') or b[2].endswith('HD') else b

chosen = {}
for row in rows:
    sid, lang, xid, name = row
    base = xid.split('@')[0]
    meta = db.get(base)
    if not xid: skipped['zonder id'] += 1; continue
    if re.search(r'\btest\b', name, re.I): skipped['test'] += 1; continue
    if ADULT.search(name) or (meta and meta.get('is_nsfw')): skipped['erotisch'] += 1; continue
    key = feed_key(xid)
    chosen[key] = prefer(chosen[key], row) if key in chosen else row

# Proper names; add (NL)/(FR) when a channel has both language feeds.
feeds_per_base = collections.Counter(k.split('@')[0] for k in chosen)
def display(row):
    sid, lang, xid, name = row
    base, feed = xid.split('@')
    meta = db.get(base)
    label = meta['name'] if meta else re.sub(r'\s+HD$', '', name)
    if feeds_per_base[base] > 1 and re.match(r'(NL|FR)', feed):
        label += f" ({feed[:2]})"
    return label

core = [chosen.pop(feed_key(x)) for x in CORE]
assert [r[2] for r in core] == CORE, [r[2] for r in core]
lang_order = {'nl': 0, 'en': 1, 'de': 2, 'fr': 3}
rest = sorted(chosen.values(), key=lambda r: (lang_order.get(r[1], 9), display(r).casefold()))

lines = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- Generated by build-channels.py from iptv-org/epg sites/pickx.be/pickx.be.channels.xml.',
         '     Order = display order in the app: the 12 main channels, then Dutch, English, German and',
         '     French channels alphabetically. One feed per channel (SD preferred over HD); test and adult',
         '     channels are left out. Channels without programmes are hidden by the app. -->',
         '<channels>']
for sid, lang, xid, name in core + rest:
    lines.append(f'  <channel site="pickx.be" site_id="{sid}" lang="{lang}" xmltv_id="{xid}">{escape(display((sid,lang,xid,name)))}</channel>')
lines.append('</channels>')
open(out_path, 'w').write('\n'.join(lines) + '\n')

meta = [{
    'id': xid,
    'language': lang,
    'categories': (db.get(xid.split('@')[0]) or {}).get('categories') or [],
} for sid, lang, xid, name in core + rest]
with open(meta_path, 'w') as f:
    json.dump({'channels': meta}, f, ensure_ascii=False, indent=1)
    f.write('\n')
print(f"{len(core) + len(rest)} zenders; overgeslagen: {dict(skipped)}; dubbels samengevoegd: {len(rows) - sum(skipped.values()) - len(core) - len(rest)}")
print(collections.Counter(r[1] for r in core + rest))
